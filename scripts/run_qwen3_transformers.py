#!/usr/bin/env python3
# Runs on the Python 3.14.6 of the AWS Neuron image, whose Neuron stack is:
#   torch-neuronx==2.14.3.0.1+b1b6c66
#   neuronx-cc==2.28.7631.0+8f7b0cf5
#   nki==0.7.0+37713544100.gfede04bb
#   torch==2.14.0
# with these on top, installed without replacing any of the image's packages:
#   pip install -c <(pip list --format=freeze) transformers==5.22.2 accelerate==1.15.0 huggingface_hub
"""Compile-mode support test for Qwen/Qwen3-0.6B (runner=run_dense, tp=1).

Auto-generated by render_run_script.py (mode=compile) — do not edit by hand.
The prompt stays on the host, with chunked prefill + StaticCache +
CompileConfig(backend="neuron"). The load
class follows the runner: run_dense uses AutoModelForCausalLM, run_multimodal
uses AutoModelForImageTextToText.

Rendered on Neuron driver 2.31.6.0.

Run with:
    python3 run.py
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
import time
import traceback

from huggingface_hub import snapshot_download

MODEL_ID = "Qwen/Qwen3-0.6B"
TP = 1
RUNNER = "run_dense"
MAX_NEW_TOKENS = 32
PROMPT = "The future of AI is"
PREFILL_CHUNK_SIZE = 512
MAX_SEQ_LEN = 1024

# nki builds its kernels for LNC=1 unless told otherwise, while torch-neuronx
# compiles for the hardware's LNC (2 on trn2): the first NKI kernel then fails
# to compile at init_process_group. Inherited by the torchrun ranks.
os.environ.setdefault("NEURON_LOGICAL_NC_CONFIG", "2")

# The model is downloaded once (parent process, before the ranks launch) into
# this local-disk dir, and every rank loads explicitly from it. Overridable
# like UV_CACHE_DIR; kept off the NFS $HOME on purpose.
LOCAL_DIR = os.path.join(
    os.environ.get("SWEEP_MODEL_DIR", "/tmp/sweep-models"),
    MODEL_ID.replace("/", "__"),
)


def relaunch_via_torchrun() -> None:
    if os.environ.get("LOCAL_RANK") is not None:
        return
    # Parent process. Download the model once (no concurrency) into LOCAL_DIR,
    # then launch the ranks — each loads explicitly from LOCAL_DIR. If ranks
    # instead load by repo id, they all resolve files against the HF cache at
    # once; on an NFS $HOME (~/.cache/huggingface) that concurrent resolution
    # races and some ranks raise a spurious "does not appear to have a file
    # named ..." OSError. A local-disk dir of real files sidesteps the cache
    # entirely. Reclaim the disk afterwards so peak usage is one model at a time.
    snapshot_download(MODEL_ID, local_dir=LOCAL_DIR)
    cmd = [
        sys.executable,
        "-m",
        "torch.distributed.run",
        f"--nproc-per-node={TP}",
        os.path.abspath(__file__),
    ]
    try:
        rc = subprocess.call(cmd)
    finally:
        shutil.rmtree(LOCAL_DIR, ignore_errors=True)
    raise SystemExit(rc)


def banner(rank: int, msg: str) -> None:
    if rank == 0:
        print(f"[support] {msg}", flush=True)


def fail_banner(rank: int, msg: str) -> None:
    # Failures print on EVERY rank, tagged with the rank id. A crash on a
    # non-zero rank must not be swallowed — rank-0-only logging turns it into an
    # opaque rc=1 with no traceback.
    print(f"[support][rank{rank}] {msg}", flush=True)


def drop_source_locations() -> None:
    # Workaround for https://github.com/aws-neuron/torch-neuronx/issues/1027,
    # to drop once it is fixed. torch-neuronx hashes the MLIR of a compiled
    # graph into its NEFF cache key, and torch-mlir gives each op the file and
    # line of every frame of its stack trace: the key would depend on where
    # transformers is installed. The ops keep their module hierarchy as location.
    from torch_mlir.extras.fx_importer import ContextCache

    ContextCache.get_node_location = lambda self, node: None


def run() -> int:
    """Compile-mode load + 8-token generate. Returns 0 on PASS, 1 on FAIL."""
    import torch
    import torch.distributed as dist
    from torch.distributed import DeviceMesh
    from transformers import (
        AutoModelForCausalLM,
        AutoConfig,
        AutoTokenizer,
        GenerationConfig,
    )
    from transformers.generation.configuration_utils import CompileConfig

    drop_source_locations()
    if not dist.is_initialized():
        dist.init_process_group(backend="neuron")
    rank = dist.get_rank()
    world_size = dist.get_world_size()

    banner(rank, f"=== {MODEL_ID} (tp={world_size}, compile) ===")

    device_mesh = DeviceMesh("neuron", list(range(world_size)))

    t0 = time.time()
    try:
        if world_size > 1:
            model = AutoModelForCausalLM.from_pretrained(
                LOCAL_DIR,
                dtype=torch.bfloat16,
                trust_remote_code=True,
                distributed_config={"tp_plan": "auto", "tp_size": world_size},
                device_mesh=device_mesh,
            )
        else:
            model = AutoModelForCausalLM.from_pretrained(
                LOCAL_DIR,
                dtype=torch.bfloat16,
                trust_remote_code=True,
            ).to("neuron")
    except Exception as exc:
        fail_banner(rank, f"LOAD FAILED after {time.time()-t0:.1f}s: {type(exc).__name__}: {exc}")
        traceback.print_exc()
        return 1
    banner(rank, f"load OK ({time.time()-t0:.1f}s)")

    model.eval()
    # GemmaTokenizer documents add_bos_token=True but inherits the tokenizers
    # backend's False, so a repo that omits the flag (gemma-4) tokenizes the
    # prompt without the <bos> the model was trained with.
    from transformers import GemmaTokenizer

    _gemma_init = GemmaTokenizer.__init__

    def _gemma_init_with_bos(self, *args, **kwargs):
        kwargs.setdefault("add_bos_token", True)
        _gemma_init(self, *args, **kwargs)

    GemmaTokenizer.__init__ = _gemma_init_with_bos
    # transformers overrides the tokenizer class some Hub repos misdeclare
    # (deepseek-coder) by matching the config's name against their repo ids,
    # which LOCAL_DIR never matches.
    tok_config = AutoConfig.from_pretrained(LOCAL_DIR, trust_remote_code=True)
    tok_config._name_or_path = MODEL_ID
    tok = AutoTokenizer.from_pretrained(LOCAL_DIR, config=tok_config, trust_remote_code=True)
    if tok.pad_token is None:
        tok.pad_token = tok.eos_token
    # Left-padding is required because the generation loop appends new
    # tokens to input_ids (`torch.cat([input_ids, next_tokens[:, None]], -1)`
    # in `_sample`). With right-padding, those appended tokens land
    # AFTER the pad/EOS region, breaking the sequence; with left-padding
    # the real prompt sits at the end and the appended tokens extend it
    # cleanly.
    tok.padding_side = "left"
    # Pad the prompt to a multiple of PREFILL_CHUNK_SIZE so the prefill
    # compiles one stable chunk graph regardless of prompt length. The prompt
    # stays on the host: `_sample` grows input_ids on the prompt's device, and
    # generate() moves only the per-step model inputs to the Neuron device.
    enc = tok.apply_chat_template(
        [{"role": "user", "content": PROMPT}],
        add_generation_prompt=True,
        padding=True,
        tokenizer_kwargs={"pad_to_multiple_of": PREFILL_CHUNK_SIZE},
        return_tensors="pt",
    )

    compile_config = CompileConfig(backend="neuron", fullgraph=False, dynamic=False)

    gen_config = GenerationConfig(
        max_new_tokens=MAX_NEW_TOKENS,
        do_sample=False,
        use_cache=True,
        prefill_chunk_size=PREFILL_CHUNK_SIZE,
        compile_config=compile_config,
        cache_implementation="static",
        # Top-level field, not `cache_config`: on the static path transformers
        # reads `cache_config` only for `QuantizedCache`, so passing the ceiling
        # there leaves the cache sized to `max_length - 1`.
        max_cache_len=MAX_SEQ_LEN,
        pad_token_id=tok.pad_token_id,
        eos_token_id=tok.eos_token_id,
    )

    t0 = time.time()
    try:
        with torch.no_grad():
            out = model.generate(
                enc["input_ids"],
                attention_mask=enc["attention_mask"],
                generation_config=gen_config,
            )
    except Exception as exc:
        fail_banner(rank, f"GENERATE FAILED after {time.time()-t0:.1f}s: {type(exc).__name__}: {exc}")
        traceback.print_exc()
        return 1

    if rank == 0:
        # Decode only the newly generated tokens (skip the left-padded +
        # prompt prefix) so the RESULTS.md notes column shows real content
        # instead of leading EOS pad bytes. Special tokens are kept, in the
        # prompt and the output alike: they delimit a chat reply's envelope (a
        # reasoning block, harmony channels), which the output check strips
        # before judging the text.
        prompt_len = enc["input_ids"].shape[1]
        prompt_text = tok.decode(enc["input_ids"][0][enc["attention_mask"][0].bool()], skip_special_tokens=False)
        gen_text = tok.decode(out[0, prompt_len:], skip_special_tokens=False)
        banner(rank, f"PASS — generated in {time.time()-t0:.1f}s")
        banner(rank, f"prompt: {prompt_text!r}")
        banner(rank, f"output: {gen_text!r}")

        # A miscompiled kernel can corrupt the output without raising: the same
        # generate() on CPU, from the same checkpoint and prompt, is the reference.
        import copy

        t0 = time.time()
        try:
            cpu_model = AutoModelForCausalLM.from_pretrained(LOCAL_DIR, dtype=torch.bfloat16, trust_remote_code=True)
            cpu_model.eval()
            cpu_config = copy.deepcopy(gen_config)
            cpu_config.disable_compile = True
            cpu_config.return_dict_in_generate = True
            cpu_config.output_scores = True
            with torch.no_grad():
                cpu_out = cpu_model.generate(
                    enc["input_ids"],
                    attention_mask=enc["attention_mask"],
                    generation_config=cpu_config,
                )
        except Exception as exc:
            banner(rank, f"cpu match: ? ({type(exc).__name__}: {exc})")
            traceback.print_exc()
            return 0
        neuron_ids = out[0, prompt_len:].tolist()
        cpu_ids = cpu_out.sequences[0, prompt_len:].tolist()
        banner(rank, f"cpu output ({time.time()-t0:.1f}s): {tok.decode(cpu_ids, skip_special_tokens=False)!r}")
        diverge = next((i for i, (n, c) in enumerate(zip(neuron_ids, cpu_ids)) if n != c), None)
        if diverge is None and len(neuron_ids) != len(cpu_ids):
            diverge = min(len(neuron_ids), len(cpu_ids))
        if diverge is None:
            banner(rank, "cpu match: Y")
        else:
            neuron_tok = tok.decode(neuron_ids[diverge : diverge + 1]) or "<end>"
            cpu_tok = tok.decode(cpu_ids[diverge : diverge + 1]) or "<end>"
            # How far the CPU ranks Neuron's token below its own choice: within
            # NEAR_TIE_GAP logits, CPU and Neuron rounding can flip the greedy pick.
            NEAR_TIE_GAP = 1.0
            gap = None
            if diverge < min(len(neuron_ids), len(cpu_ids), len(cpu_out.scores)):
                scores = cpu_out.scores[diverge][0].float()
                gap = (scores[cpu_ids[diverge]] - scores[neuron_ids[diverge]]).item()
            verdict = "~ near-tie" if gap is not None and gap <= NEAR_TIE_GAP else "N"
            gap_text = "?" if gap is None else f"{gap:.3f}"
            banner(
                rank,
                f"cpu match: {verdict} at token {diverge} (neuron {neuron_tok!r}, cpu {cpu_tok!r}, cpu logit gap {gap_text})",
            )
    return 0


def main() -> None:
    relaunch_via_torchrun()
    raise SystemExit(run())


if __name__ == "__main__":
    main()
